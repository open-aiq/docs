"""Copies the app's Material icons into src/data/icons.json as SVG paths.

The mobile app draws these icons from Flutter's bundled Material Icons font,
so the web dashboard and the docs use the very same glyphs. Run it from docs/
when the icon set changes (needs Flutter and `pip install fonttools`):

    make icons:sync

Material Icons are by Google, under the Apache License 2.0.
"""

import json
import re
import shutil
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

# Semantic name used by the web and docs -> Flutter's Icons.<name>.
ICONS = {
    "pm25": "grain",
    "pm1": "bubble_chart_outlined",
    "pm10": "blur_on",
    "feelsLike": "wb_sunny_outlined",
    "temperature": "thermostat_outlined",
    "humidity": "water_drop_outlined",
    "outdoor": "park_outlined",
    "indoor": "home_outlined",
    "online": "wifi",
    "offline": "wifi_off",
    "public": "public",
    "private": "lock_outline",
    "update": "system_update",
    "cloudOff": "cloud_off_outlined",
}


def flutter_root() -> Path:
    if len(sys.argv) > 1:
        return Path(sys.argv[1])
    flutter = shutil.which("flutter")
    if not flutter:
        sys.exit("Flutter isn't on PATH. Pass the Flutter SDK path as the first argument.")
    return Path(flutter).resolve().parent.parent


def main() -> None:
    root = flutter_root()
    font = TTFont(root / "bin/cache/artifacts/material_fonts/MaterialIcons-Regular.otf")
    source = (root / "packages/flutter/lib/src/material/icons.dart").read_text()
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    upm = font["head"].unitsPerEm
    ascent = font["hhea"].ascent

    icons = {}
    for name, flutter_name in ICONS.items():
        match = re.search(
            rf"static const IconData {flutter_name} = IconData\((0x[0-9a-f]+)", source
        )
        if not match:
            sys.exit(f"Icons.{flutter_name} isn't in this Flutter SDK.")
        glyph = cmap[int(match.group(1), 16)]
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
        # Font coordinates grow upwards; SVG's grow downwards.
        glyphs[glyph].draw(TransformPen(pen, (1, 0, 0, -1, 0, ascent)))
        icons[name] = {"flutter": f"Icons.{flutter_name}", "path": pen.getCommands()}

    out = {
        "$description": "Material icons shared by the app, the web dashboard and the docs. "
        "Generated by scripts/extract-icons.py from Flutter's Material Icons font "
        "(Google, Apache License 2.0). Don't edit by hand.",
        "viewBox": f"0 0 {upm} {upm}",
        "icons": icons,
    }
    Path("src/data/icons.json").write_text(json.dumps(out, indent=2) + "\n")
    print(f"Wrote src/data/icons.json ({len(icons)} icons)")


if __name__ == "__main__":
    main()
